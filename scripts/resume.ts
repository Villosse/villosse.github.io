// Generate resume/resume.typ from config.yaml and projects/*.yaml. Usage: node scripts/resume.ts
// The phone number is never stored in the repo: it comes from RESUME_PHONE.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { loadConfig } from '../src/config/load.ts';
import type { Highlight } from '../src/config/schema.ts';
import { escapeTypst, toTypst, typstString } from '../src/utils/richtext.ts';

const root = new URL('..', import.meta.url);
const outDir = new URL('resume/', root);
const read = (url: URL) => (existsSync(url) ? readFileSync(url, 'utf8') : undefined);
const config = loadConfig(read(new URL('config.yaml', root)) ?? '', (slug) => read(new URL(`projects/${slug}.yaml`, root)));

const onResume = <T extends { resume: boolean }>(xs: T[] = []) => xs.filter((x) => x.resume);

// "https://www.github.com/Foo/" -> "github.com/Foo"
const displayUrl = (url: string) => url.replace(/^\w+:\/\/(www\.)?/, '').replace(/\/$/, '');
const link = (url: string, label = displayUrl(url)) => `#link(${typstString(url)})[${escapeTypst(label)}]`;

const bullets = (hs: Highlight[] = [], indent = ''): string[] =>
  hs.flatMap((h) =>
    typeof h === 'string'
      ? [`${indent}- ${toTypst(h)}`]
      : [`${indent}- ${toTypst(h.text)}`, ...bullets(h.items, indent + '  ')],
  );

const entry = (left: string, right: string) => `#entry[${left}][${escapeTypst(right)}]`;

const section = (title: string, lines: string[]) => (lines.length ? ['', `= ${title}`, '', ...lines] : []);

const { personal, contact } = config;
const fullName = `${personal.name} ${personal.surname}`;

const phone = process.env.RESUME_PHONE?.trim();
if (!phone) console.warn('warning: RESUME_PHONE is not set, the resume will have no phone number');

const contactLine = [
  personal.location && escapeTypst(personal.location),
  personal.citizenship && escapeTypst(personal.citizenship),
  phone && escapeTypst(phone).replace(/ /g, '~'),
  contact.email && link(`mailto:${contact.email}`, contact.email),
  contact.github && link(contact.github),
  contact.linkedin && link(contact.linkedin),
  contact.website && link(contact.website),
].filter(Boolean);

const out = [
  '// Generated by scripts/resume.ts from config.yaml. Do not edit.',
  '#import "template.typ": *',
  '',
  `#show: resume.with(name: ${typstString(fullName)})`,
  '',
  `#align(center)[${contactLine.join(' | ')}]`,

  ...section('Summary', personal.summary ? [toTypst(personal.summary)] : []),

  ...section('Education', onResume(config.education).flatMap((e) => [
    entry(`*${escapeTypst([e.institution, e.location].filter(Boolean).join(', '))}* – ${toTypst(e.degree)}`, e.year),
    ...bullets(e.highlights),
  ])),

  ...section('Experience', onResume(config.experience).flatMap((e) => [
    entry(`*${escapeTypst(e.position)},* ${escapeTypst(e.company)}${e.location ? ` – ${escapeTypst(e.location)}` : ''}`, e.duration),
    ...bullets(e.highlights),
    '',
  ])),

  ...section('Projects', onResume(config.projects).flatMap((p) => [
    entry(`*${escapeTypst(p.title)}*${p.role ? ` – ${toTypst(p.role)}` : ''}${p.link ? ` (${link(p.link)})` : ''}`, p.date ?? ''),
    ...bullets(p.highlights),
    '',
  ])),

  ...section('Volunteering', onResume(config.volunteering).flatMap((v) => [
    `- *${escapeTypst(v.organization)}* – ${toTypst(v.description)} (${escapeTypst(v.duration)})`,
    ...bullets(v.highlights, '  '),
  ])),

  ...section('Skills', config.skills.map((g, i, gs) =>
    `*${escapeTypst(g.name)}:* ${g.items.map(escapeTypst).join(', ')}${i < gs.length - 1 ? ' \\' : ''}`,
  )),
  '',
];

writeFileSync(new URL('resume.typ', outDir), out.join('\n'));
console.log('wrote resume/resume.typ');
